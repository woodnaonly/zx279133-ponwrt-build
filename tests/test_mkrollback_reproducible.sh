#!/bin/sh
# 本地排演套件（local rehearsal suite）：依赖 staging/ 下的真实构建产物，
# 在只 clone 本仓库的环境里跑不起来，也**没有**接进 CI。
# 为什么、怎么跑、缺的那个夹具从哪来：同目录 README.md。
# Can the rollback pair be REGENERATED, and does the generator reproduce exactly the bytes
# this session verified?
#
# Everything claimed about rollback so far rests on staging/rollback/{flash-uImage,flash-dtb.bin}.
# Those were checked by hand. tools/mkrollback.sh is what produces them, from the partition
# dumps in staging/ctl/. If the generator no longer reproduces those bytes - or if it cannot
# run at all - then "rollback is ready" is a claim about a file nobody can regenerate, which
# is a different and much weaker thing.
#
# PERMIT is pointed at a temp file so the real staging/ctl/flash.permit is not appended to.
set -u
cd /mnt/c/ugit/SK-D840N4
export LC_ALL=C
pass=0; fail=0
ok()  { printf '  PASS  %-52s %s\n' "$1" "${2:-}"; pass=$((pass+1)); }
bad() { printf '  FAIL  %-52s %s\n' "$1" "${2:-}"; fail=$((fail+1)); }
note(){ printf '  ....  %-52s %s\n' "$1" "${2:-}"; }
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT

echo "=== 0. the generator's inputs are present ==="
for f in staging/ctl/mtd2.bin staging/ctl/mtd3.bin; do
	if [ -f "$f" ]; then ok "$f exists" "$(wc -c <"$f") bytes"
	else bad "$f exists" "mkrollback.sh cannot run without it"; fi
done

echo
echo "=== 1. the pair currently on disk, before anything runs ==="
for f in staging/rollback/flash-uImage staging/rollback/flash-dtb.bin; do
	[ -f "$f" ] && ok "$(basename "$f") present" "$(wc -c <"$f") B  md5 $(md5sum <"$f" | cut -c1-32)" \
	            || bad "$(basename "$f") present" ""
done
cp staging/rollback/flash-uImage  "$T/before-uImage"  2>/dev/null || true
cp staging/rollback/flash-dtb.bin "$T/before-dtb"    2>/dev/null || true

echo
echo "=== 2. run the generator into a scratch directory ==="
mkdir -p "$T/rollback"
# the script hard-codes OUT=staging/rollback, so keep the real pair safe and restore after
cp -a staging/rollback/flash-uImage staging/rollback/flash-dtb.bin "$T/keep-" 2>/dev/null || true
mkdir -p "$T/keepdir" && cp staging/rollback/flash-uImage staging/rollback/flash-dtb.bin "$T/keepdir/" 2>/dev/null
# OUT is named explicitly (mkrollback.sh honours it) because the tool cds to its own repository
# root first: left relative it would write to ci-build-repo/staging/rollback, and every
# comparison below would be against the workspace copy that nothing had regenerated - which
# compares equal by doing nothing at all.
OUT=$(OUT="$PWD/staging/rollback" LOCAL="$PWD" SKIP_BOARD=1 PERMIT="$T/permit.txt" \
      sh ci-build-repo/tools/mkrollback.sh 2>&1); rc=$?
printf '%s\n' "$OUT" | sed 's/^/    /'
if [ "$rc" -eq 0 ]; then ok "mkrollback.sh runs clean" "rc=0"
else bad "mkrollback.sh runs clean" "rc=$rc"; fi

echo
echo "=== 3. does it reproduce the verified bytes exactly? ==="
for pair in "flash-uImage before-uImage" "flash-dtb.bin before-dtb"; do
	set -- $pair
	f=$1; b=$2
	if cmp -s "staging/rollback/$f" "$T/$b"; then
		ok "$f regenerated byte-for-byte" "$(md5sum <"staging/rollback/$f" | cut -c1-32)"
	elif [ -f "$T/$b" ]; then
		bad "$f regenerated byte-for-byte" "before $(md5sum <"$T/$b" | cut -c1-32) after $(md5sum <"staging/rollback/$f" | cut -c1-32)"
	else
		bad "$f regenerated byte-for-byte" "no prior copy to compare against"
	fi
done

echo
echo "=== 4. and does the regenerated pair still equal the pre-flash dumps? ==="
T1="$T/k"; gzip -dc backups/preflash-20261013/mtd2-kernel.bin.gz >"$T1" 2>/dev/null
if head -c "$(wc -c <staging/rollback/flash-uImage)" "$T1" | cmp -s - staging/rollback/flash-uImage; then
	ok "regenerated kernel is a prefix of pre-flash mtd2" ""
else
	bad "regenerated kernel is a prefix of pre-flash mtd2" ""
fi
T2="$T/d"; gzip -dc backups/preflash-20261013/mtd3-dtb.bin.gz >"$T2" 2>/dev/null
if head -c "$(wc -c <staging/rollback/flash-dtb.bin)" "$T2" | cmp -s - staging/rollback/flash-dtb.bin; then
	ok "regenerated dtb is a prefix of pre-flash mtd3" ""
else
	bad "regenerated dtb is a prefix of pre-flash mtd3" ""
fi

echo
echo "=== 5. the carve is exact: no padding carried into the image ==="
python3 - <<'PY'
import struct
k = open("staging/rollback/flash-uImage","rb").read()
magic, hcrc, ctime, dsize, load, ep, dcrc = struct.unpack(">7I", k[:28])
name = k[32:64].split(b"\0")[0].decode("latin1")
print("  uImage magic 0x%08x  name=%r" % (magic, name))
print("  declared data size %d, file is %d -> %s" % (dsize, len(k),
      "exact" if len(k) == 64 + dsize else "MISMATCH"))
print("  gzip body: %s" % ("yes" if k[64:66] == b"\x1f\x8b" else "NO"))
d = open("staging/rollback/flash-dtb.bin","rb").read()
totalsize, = struct.unpack(">I", d[4:8])
print("  FDT totalsize %d, file is %d -> %s" % (totalsize, len(d),
      "exact" if len(d) == totalsize else "MISMATCH"))
PY

echo
echo "=== 6. the permit record it writes ==="
if [ -f "$T/permit.txt" ]; then
	sed 's/^/  /' "$T/permit.txt"
	grep -q 'proven=' "$T/permit.txt" && ok "the permit line records how the bytes were proven" "" \
		|| bad "permit line" "no proven= field"
else
	note "no permit written" "SKIP_BOARD=1 with no usable snapshot"
fi
echo "  (the real staging/ctl/flash.permit was not touched: PERMIT pointed at a temp file)"
echo "  live entries in the real permit: $(wc -l <staging/ctl/flash.permit 2>/dev/null || echo '?')"

echo
echo "=== pass=$pass fail=$fail ==="
# mkrollback.sh writes into staging/rollback in place. It reproduced the bytes exactly
# this time, but a future run that produced something different would leave that on disk -
# put the originals back so this test is never the thing that changes the rollback pair.
if [ -f "$T/keepdir/flash-uImage" ] && [ -f "$T/keepdir/flash-dtb.bin" ]; then
	if ! cmp -s "$T/keepdir/flash-uImage" staging/rollback/flash-uImage; then
		cp "$T/keepdir/flash-uImage" staging/rollback/flash-uImage
		echo "  (restored staging/rollback/flash-uImage to its pre-test bytes)"
	fi
	if ! cmp -s "$T/keepdir/flash-dtb.bin" staging/rollback/flash-dtb.bin; then
		cp "$T/keepdir/flash-dtb.bin" staging/rollback/flash-dtb.bin
		echo "  (restored staging/rollback/flash-dtb.bin to its pre-test bytes)"
	fi
fi
[ "$fail" -eq 0 ] || exit 1
exit 0