// Isolated ONU shell client: own sync markers + own output file, so it cannot
// collide with other sessions sharing /var/.o on the device.
//   ONU_PASS=... node onu2.cjs backup <idx:name:size> [<idx:name:size> ...]
const net = require('net');
const fs = require('fs');
const crypto = require('crypto');

const HOST = process.env.ONU_HOST || '192.168.9.1';
const PC_IP = process.env.PC_IP || '192.168.1.2';
const PORT = Number(process.env.PULL_PORT || 9820);
const OUT = '/var/.o_qd';
const TAG = 'QD';
const IAC = 255, WILL = 251, WONT = 252, DO = 253, DONT = 254, SB = 250, SE = 240;

class Telnet {
  constructor(sock) {
    this.sock = sock; this.buf = Buffer.alloc(0); this.out = ''; this.waiters = [];
    sock.on('data', (d) => this.feed(d));
  }
  feed(chunk) {
    this.buf = Buffer.concat([this.buf, chunk]);
    while (this.buf.length) {
      const i = this.buf.indexOf(IAC);
      if (i === -1) { this.out += this.buf.toString('utf8'); this.buf = Buffer.alloc(0); break }
      this.out += this.buf.slice(0, i).toString('utf8'); this.buf = this.buf.slice(i);
      if (this.buf.length < 3) break;
      const cmd = this.buf[1];
      if (cmd === IAC) { this.out += '\xff'; this.buf = this.buf.slice(2); continue }
      if (cmd === SB) { const se = this.buf.indexOf(Buffer.from([IAC, SE])); if (se === -1) break; this.buf = this.buf.slice(se + 2); continue }
      const opt = this.buf[2]; this.buf = this.buf.slice(3);
      if (cmd === DO) this.sock.write(Buffer.from([IAC, WONT, opt]));
      else if (cmd === WILL) this.sock.write(Buffer.from([IAC, DONT, opt]));
    }
    this.check();
  }
  check() {
    this.waiters = this.waiters.filter((w) => {
      if (w.re.test(this.out)) { clearTimeout(w.t); w.res(); return false }
      return true;
    });
  }
  expect(re, ms) {
    return new Promise((res, rej) => {
      if (re.test(this.out)) return res();
      const w = { re, res };
      w.t = setTimeout(() => rej(new Error('timeout /' + re.source + '/ tail=' + JSON.stringify(this.out.slice(-160)))), ms);
      this.waiters.push(w);
    });
  }
  send(s) { this.sock.write(String(s) + '\r\n') }
  drain() { this.out = '' }
}

let seq = 0;
// Marker is generated by the device (`echo QD$(( N ))` prints QD<N>) and its own
// echo of the command line stays literal, so the regex can only match real output.
async function sync(tn, ms) {
  const n = ++seq;
  tn.send(`echo ${TAG}$(( ${n} ))`);
  await tn.expect(new RegExp(`^${TAG}${n}$`, 'm'), ms);
}

async function run(tn, cmd, ms = 120000) {
  await sync(tn, ms);
  tn.drain();
  tn.send(`{ ${cmd}; } > ${OUT} 2>&1; echo rc-$?`);
  await sync(tn, ms);
  tn.drain();
  tn.send(`cat ${OUT}; echo ${TAG}EOF`);
  await tn.expect(new RegExp(`^${TAG}EOF$`, 'm'), ms);
  return tn.out.replace(/\r/g, '').split('\n').filter((l) => !new RegExp(`^${TAG}`).test(l) && !/^cat /.test(l)).join('\n').trim();
}

function md5(file) {
  return crypto.createHash('md5').update(fs.readFileSync(file)).digest('hex');
}

function listen(port, dest, ms) {
  // Buffer in RAM and writeFileSync at the end: a WriteStream can report success
  // while the file on disk stays short, which silently produced 0-byte backups.
  return new Promise((resolve, reject) => {
    const chunks = [];
    let size = 0, settled = false;
    const t = setTimeout(() => {
      if (settled) return; settled = true;
      srv.close();
      reject(new Error(`transfer timeout after ${size} bytes`));
    }, ms);
    const srv = net.createServer((cl) => {
      cl.on('data', (d) => { chunks.push(d); size += d.length });
      cl.on('error', () => {});
      cl.on('close', () => {
        if (settled) return; settled = true; clearTimeout(t); srv.close();
        const buf = Buffer.concat(chunks);
        fs.writeFileSync(dest, buf, { flush: true });
        const md5 = crypto.createHash('md5').update(fs.readFileSync(dest)).digest('hex');
        const onDisk = fs.statSync(dest).size;
        if (onDisk !== buf.length) throw new Error(`writeback size ${onDisk} != ${buf.length}`);
        resolve({ size: onDisk, md5 });
      });
    });
    srv.on('error', (e) => { if (settled) return; settled = true; clearTimeout(t); reject(e) });
    srv.listen(port, '0.0.0.0');
  });
}

(async () => {
  const mode = process.argv[2];
  const items = process.argv.slice(3);
  const sock = net.createConnection({ host: HOST, port: 23 });
  const tn = await new Promise((res, rej) => {
    sock.once('error', rej);
    sock.once('connect', async () => {
      const t = new Telnet(sock);
      await t.expect(/login\s*:/i, 10000);
      t.send(process.env.ONU_USER || 'root');
      await t.expect(/password\s*:/i, 8000);
      t.send(process.env.ONU_PASS);
      await new Promise((r) => setTimeout(r, 1500));
      t.drain(); res(t);
    });
  });
  if (mode !== 'backup') { console.log(await run(tn, mode)); sock.destroy(); return }

  fs.mkdirSync('backups', { recursive: true });
  for (const it of items) {
    const [idx, name, sz, start, len] = it.split(':');
    // Chunked dumps need per-chunk temp files (tmpfs on the device is only 80 MiB).
    const dev = `/var/skb_${start === undefined ? idx : name}.bin`;
    const local = `backups/${start === undefined ? name : name + '_' + start}.bin`;
    const range = start === undefined ? '' : `-s ${start} -l ${len}`;
    const t0 = Date.now();
    const dump = await run(tn, `nanddump ${range} -f ${dev} /dev/mtd${idx} >/dev/null 2>&1; sync; md5sum ${dev}; ls -l ${dev} | awk '{print $5}'`, 300000);
    const m = dump.match(/([0-9a-f]{32})\s/) || [];
    const expect = Number(len || sz);
    console.log(`[${name}] dumped  device-md5=${m[1]}  bytes=${expect}  (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
    const p = listen(PORT, local, 600000);
    try {
      await run(tn, `nc ${PC_IP} ${PORT} < ${dev}`, 600000);
    } catch (e) { console.log(`[${name}] push failed: ${e.message}`); }
    const got = await p;
    const ok = got.md5 === m[1] && got.size === expect;
    console.log(`[${name}] local    pc-md5=${got.md5}  bytes=${got.size}  -> ${ok ? 'VERIFIED' : '*** MISMATCH ***'}`);
    await run(tn, `rm -f ${dev}; df -h /var | tail -1 | awk '{print "device /var free: "$4}'`, 60000);
    if (!ok) { console.log(`[${name}] ABORT: readback differs`); break }
  }
  sock.destroy();
})().catch((e) => { console.error('FATAL ' + e.message); process.exit(1) });
